"""Regenerate app/embedded.py from the data/ directory.

data/ is the source of truth, but a build may not copy it into the image, so the
service keeps an embedded copy of its cases, golden expectations and policy text.
This script keeps that copy in sync; tests/test_seed.py asserts it is up to date.

Run: python tools/embed.py
"""

from __future__ import annotations

import json
import pprint
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DATA = REPO / "data"
OUT = REPO / "app" / "embedded.py"

HEADER = '''"""Generated by tools/embed.py from data/ — do not edit by hand.

Tests assert this file matches data/cases/*.json, data/eval/golden.json and
data/policy/rules.md, so the service still works if a build omits data/.
"""
'''


def load_cases() -> list[dict]:
    packets = []
    for path in sorted((DATA / "cases").glob("*.json")):
        packets.append(json.loads(path.read_text(encoding="utf-8")))
    return packets


def load_golden() -> list[dict]:
    data = json.loads((DATA / "eval" / "golden.json").read_text(encoding="utf-8"))
    return data["cases"]


def load_policy() -> str:
    return (DATA / "policy" / "rules.md").read_text(encoding="utf-8")


def render() -> str:
    cases = pprint.pformat(load_cases(), width=110, sort_dicts=False)
    golden = pprint.pformat(load_golden(), width=110, sort_dicts=False)
    policy = load_policy()
    return (
        HEADER
        + "\nDEFAULT_CASES: list[dict] = " + cases + "\n\n"
        + "DEFAULT_GOLDEN: list[dict] = " + golden + "\n\n"
        + "POLICY_MARKDOWN: str = " + repr(policy) + "\n"
    )


def main() -> int:
    content = render()
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
